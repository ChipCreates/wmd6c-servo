"""
Generate the WM-D6C Power Board schematic and its project symbol library:

  hardware/kicad/Power-Board/wm-d6c-power-board/wm-d6c-power-board.kicad_sch
  hardware/kicad/Power-Board/wm-d6c-power-board/wm-d6c-power-board.kicad_sym
  hardware/kicad/Power-Board/wm-d6c-power-board/sym-lib-table

Authority: docs/hardware/kicad-power-board-guide.md (locked Rev A).
Component values come from the TI / Fortune datasheets in hardware/datasheets/.

Usage:  python3 tools/gen_power_board.py
"""
import copy
import sys
import tempfile
from collections import defaultdict
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))
from kicad_sch import (Libraries, Part, Sheet, Str, box_symbol, find, parse,  # noqa: E402
                       write_sym_lib_table, write_symbol_lib)

ROOT = Path(__file__).resolve().parent.parent
PROJ = ROOT / "hardware/kicad/Power-Board/wm-d6c-power-board"
OUT = PROJ / "wm-d6c-power-board.kicad_sch"
LIB = PROJ / "wm-d6c-power-board.kicad_sym"
NICK = "PowerBoard"
ROOT_UUID = "b30cb928-1d92-4d62-ae48-ad44a14cff65"     # keep the project's root sheet UUID

# ---------------------------------------------------------------- project library
tps = box_symbol(
    "TPS63070RNM", "U", "TPS63070RNM",
    left=[(["12", "13"], "VIN", "power_in"), ("14", "EN", "input"), ("1", "PS/SYNC", "input"),
          ("15", "VSEL", "input"), ("11", "L1", "passive")],
    right=[(["7", "8"], "VOUT", "power_out"), ("5", "FB", "input"), ("6", "FB2", "passive"),
           ("2", "PG", "open_collector"), ("3", "VAUX", "passive"), ("9", "L2", "passive")],
    bottom=[("4", "GND", "power_in"), ("10", "PGND", "power_in")],
    datasheet="https://www.ti.com/lit/ds/symlink/tps63070.pdf",
    description="2-16 V input buck-boost converter, 3.6 A switch, adjustable output, VQFN-15 (RNM)",
    keywords="buck-boost converter")
fs = box_symbol(
    "FS8205A", "Q", "FS8205A",
    left=[(["2", "3"], "S1", "passive"), ("4", "G1", "input")],
    right=[(["6", "7"], "S2", "passive"), ("5", "G2", "input")],
    top=[(["1", "8"], "D12", "passive")],
    footprint="Package_SO:TSSOP-8_4.4x3mm_P0.65mm",
    datasheet="https://www.ic-fortune.com/upload/Download/FS8205A-DS-17_EN.pdf",
    description="Dual N-channel MOSFET, common drain, 20 V, for 1-cell Li-ion protection (TSSOP-8)",
    keywords="mosfet dual common drain battery protection")
dsr1 = parse((ROOT / "hardware/kicad/DSR-1/DSR-1.kicad_sym").read_text(encoding="utf-8"))
b1 = copy.deepcopy([s for s in find(dsr1, "symbol") if s[1] == "B+1"][0])
write_symbol_lib(LIB, [b1, fs, tps])
write_sym_lib_table(PROJ / "sym-lib-table", {NICK: "${KIPRJMOD}/wm-d6c-power-board.kicad_sym"})

# ---------------------------------------------------------------- schematic
libs = Libraries({NICK: LIB})
power = {"GND": "power:GND", "B+1": f"{NICK}:B+1"}
sheet = Sheet("wm-d6c-power-board", ROOT_UUID, libs, power, {
    "title": "WM-D6C Power Board (DSR-1)",
    "date": "2026-11-09",
    "rev": "A-draft1",
    "company": "wmd6c-servo (CERN-OHL-P v2)",
    "comments": [
        "Generated by tools/gen_power_board.py; authority: docs/hardware/kicad-power-board-guide.md",
        "USB-C 5 V only (no PD). 1S3P 803040 LiPo. B+1 = 6.0 V into the former battery pads.",
        "Connector families/pitch not yet chosen: generic connectors, empty footprints",
    ]})
counters = defaultdict(int)


def ref(prefix):
    counters[prefix] += 1
    return f"{prefix}{counters[prefix]}"


def R(value, a, b):
    return Part(ref("R"), "Device:R", value, {"1": a, "2": b})


def C(value, a, b="GND"):
    return Part(ref("C"), "Device:C", value, {"1": a, "2": b})


def TP(name, net):
    return Part(ref("TP"), "Connector:TestPoint", name, {"1": net})


def CONN(value, nets):
    return Part(ref("J"), f"Connector_Generic:Conn_01x{len(nets):02d}", value,
                {str(i + 1): net for i, net in enumerate(nets)}, footprint="")


def FLAG(net):
    counters["#FLG"] += 1
    return Part(f"#FLG{counters['#FLG']:02d}", "power:PWR_FLAG", "PWR_FLAG", {"1": net})


A = [CONN("USB-C power entry (VBUS, GND)", ["VBUS_5V", "GND"]), FLAG("VBUS_5V"), FLAG("GND"),
     Part(ref("D"), "Device:D_Zener", "SMAJ5.0A", {"1": "VBUS_5V", "2": "GND"}, footprint=""),
     C("10uF 16V", "VBUS_5V")]

Bz = [Part(ref("U"), "Battery_Management:BQ24074RGT", "BQ24074RGT", {
          "1": "BQ_TS", "2": "CELL_POS_RAW", "3": "CELL_POS_RAW", "4": "GND", "5": "V_SYS",
          "6": "GND", "7": "PGOOD_N", "8": "GND", "17": "GND", "9": "CHG_STAT_N",
          "10": "V_SYS", "11": "V_SYS", "12": "BQ_ILIM", "13": "VBUS_5V",
          "14": None, "15": None, "16": "BQ_ISET"}),
      R("1.13k 1%", "BQ_ISET", "GND"), R("1.13k 1%", "BQ_ILIM", "GND"), R("10k", "BQ_TS", "GND"),
      C("10uF 10V", "V_SYS"), C("10uF 10V", "CELL_POS_RAW")]

Cz = [CONN(f"LiPo cell {i} 803040 (JST PH 2-pin)", ["CELL_POS_RAW", "CELL_NEG_RAW"])
      for i in (1, 2, 3)] + [FLAG("CELL_NEG_RAW")]

D = [Part(ref("U"), "Battery_Management:DW01A", "DW01A",
          {"5": "DW_VCC", "6": "CELL_NEG_RAW", "1": "DW_OD", "3": "DW_OC", "2": "DW_CS"}),
     R("470", "CELL_POS_RAW", "DW_VCC"), C("100nF", "DW_VCC", "CELL_NEG_RAW"), FLAG("DW_VCC"),
     R("2k", "DW_CS", "GND"),
     Part(ref("Q"), f"{NICK}:FS8205A", "FS8205A", {
         "1": "PROT_FET_D", "8": "PROT_FET_D", "2": "CELL_NEG_RAW", "3": "CELL_NEG_RAW",
         "4": "DW_OD", "5": "DW_OC", "6": "GND", "7": "GND"})]

E = [Part(ref("U"), f"{NICK}:TPS63070RNM", "TPS63070RNM", {
         "12": "V_SYS", "13": "V_SYS", "14": "V_SYS", "1": "V_SYS", "15": "GND", "11": "TPS_L1",
         "7": "B+1", "8": "B+1", "5": "TPS_FB", "6": "GND", "2": None, "3": "TPS_VAUX",
         "9": "TPS_L2", "4": "GND", "10": "GND"}, footprint=""),
     Part(ref("L"), "Device:L", "1.5uH XFL4020-152ME", {"1": "TPS_L1", "2": "TPS_L2"}, footprint=""),
     R("649k 1%", "B+1", "TPS_FB"), R("100k 1%", "TPS_FB", "GND"), C("100nF", "TPS_VAUX"),
     C("10uF 25V", "V_SYS"), C("10uF 25V", "V_SYS"), C("10uF 25V 0603", "V_SYS"),
     C("22uF 16V", "B+1"), C("22uF 16V", "B+1"), C("22uF 16V", "B+1"), C("10uF 25V 0603", "B+1")]

F = [CONN("Output to WM-D6C battery pads", ["B+1", "GND"])]

G = [CONN("Servo Board telemetry", ["GND", "VBAT_SENSE", None, "CHG_STAT_N", "PGOOD_N"]),
     R("220k 1%", "CELL_POS_RAW", "VBAT_SENSE"), R("470k 1%", "VBAT_SENSE", "GND")]

T = [TP(n, net) for n, net in [
    ("TP_VBUS", "VBUS_5V"), ("TP_SYS", "V_SYS"), ("TP_CELL_POS", "CELL_POS_RAW"),
    ("TP_CELL_NEG", "CELL_NEG_RAW"), ("TP_B1", "B+1"), ("TP_CHG", "CHG_STAT_N"),
    ("TP_PGOOD", "PGOOD_N"), ("TP_GND", "GND")]]

W = 274.32
cols = [12.7, 12.7 + W + 5.08, 12.7 + 2 * (W + 5.08)]
y = 12.7
y = sheet.zone("A - USB-C power input (5 V only)", cols[0], y, W, A, notes=[
    "VBUS and GND only; D+/D-/CC belong to the Servo Board. No PD, no 9 V.",
    "SMAJ5.0A unidirectional TVS (drawn as Zener: cathode on VBUS). IN cap 1-10 uF per datasheet."]) + 5.08
y = sheet.zone("B - BQ24074 charger / power path", cols[0], y, W, Bz, notes=[
    "ICHG = 890 AOhm / 1.13k = 0.79 A.  IIN(max) = 1610 AOhm / 1.13k = 1.42 A (RILIM >= 1.1k).",
    "Requires a USB-C source rated >= 1.5 A. EN2=OUT, EN1=GND: ILIM-programmed. CE=GND.",
    "TS: 10k fixed (cells have no NTC). TMR, ITERM open: default timers, 10 % termination."])

y = 12.7
y = sheet.zone("C - 1S3P pack (3 x 803040 in parallel)", cols[1], y, W, Cz, notes=[
    "Voltage-match cells within 30-50 mV before first parallel connection."]) + 5.08
y = sheet.zone("D - Pack protection (DW01A + FS8205A)", cols[1], y, W, D, notes=[
    "Datasheet reference: R 470 Ohm + 100 nF on VCC, 2k on CS. OD -> G1 (discharge FET, S1 at",
    "cell negative); OC -> G2 (charge FET, S2 at GND). Raw cell negative reaches GND only through Q1."])

y = 12.7
y = sheet.zone("E - B+1 regulator (TPS63070, 6.0 V)", cols[2], y, W, E, notes=[
    "VOUT = 0.8 V x (1 + 649k/100k) = 5.99 V. Datasheet Fig. 10: 1.5 uH, CIN 2x10 uF + 10 uF,",
    "COUT 3x22 uF + 10 uF, VAUX 100 nF. EN, PS/SYNC = V_SYS (always on, power-save). VSEL, FB2 = GND."]) + 5.08
y = sheet.zone("F - Machine power output", cols[2], y, W, F, notes=[
    "B+1 and GND to the former battery-terminal pads; S901 remains the master switch."]) + 5.08
y = sheet.zone("G - Telemetry to Servo Board", cols[2], y, W, G, notes=[
    "VBAT_SENSE = 4.2 V x 470k/690k = 2.86 V max; always-on divider (6 uA).",
    "VBAT_SENSE_EN (pin 3) not used on this board. CHG/PGOOD are pulled up on the Servo Board."]) + 5.08
y = sheet.zone("Test points (guide 12)", cols[2], y, W, T)

sheet.write(OUT)
problems = sheet.verify(OUT, Path(tempfile.mkdtemp(prefix="pwr-")))
print(f"wrote {OUT.relative_to(ROOT)}: {len(sheet.parts)} parts, "
      f"{len(sheet.expected)} pin/net expectations, {len(problems)} netlist problems")
for p in problems:
    print("  ", p)
sys.exit(1 if problems else 0)
