    ("TP_B1", "B+1"), ("TP_B3", "B+3"), ("TP_3V3", "+3V3"), ("TP_GND", "GND"),
    ("TP_FG_RAW", "FG_RAW"), ("TP_FG_IN", "FG_IN"), ("TP_MOTOR_PWM", "MOTOR_PWM"),
